  function str(v) { return v == null ? '' : String(v); }

  function match(day, subject) {
    if (!day) return null;
    var head = (str(day.title) + ' ' + str(day.microTopic)).replace(/\s+/g, ' ');
    var subj = str(subject || day.subject).toLowerCase();
    for (var i = 0; i < ITEMS.length; i++) {
      var it = ITEMS[i];
      if (subj && it.subjects.indexOf(subj) < 0) continue;
      if (it.not && it.not.test(head)) continue;
      if (it.words.test(head)) return it;
    }
    return null;
  }

